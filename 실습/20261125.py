def dp(name):
    """실행 위치가 어디든 data 폴더를 찾아 주는 도우미 (01단원과 같은 함수)"""
    here = os.path.dirname(os.path.abspath(__file__))
    for c in (
        os.path.join("data", name),
        os.path.join(here, "data", name),
        os.path.join(here, "..", "data", name),
    ):
        if os.path.exists(c):
            return c
    return os.path.join("data", name)


