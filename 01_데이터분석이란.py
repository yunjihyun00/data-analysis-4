# sorted(pairs, ...)    pairs를 줄 세운 새 목록을 만든다(원본 pairs는 그대로)
# key=lambda t: -t[1]   "무엇을 기준으로 줄 세울까"를 알려 주는 손잡이
# lambda t: -t[1]   이름 없는 한 줄 함수, "t 를 받으면 -t[1]을 돌려준다"는 뜻
# t 는 ("온도", 1.39) 같은 한 쌍이고, t[1] 은 그 쌍의 숫자입니다.
# 앞에 붙은 마이너스    작은 것부터 세우는 게 기본이라, 부호를 뒤집어 큰 것부터 세웁니다.

