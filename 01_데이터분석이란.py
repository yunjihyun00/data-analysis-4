# {x:.2f} -> 소수 둘째 자리까지만 보여 달라. 859.5318.... 이 859.53 으로 보입니다.
# {x:10.1f} -> 10칸을 잡고 그 안에서 첫째 자리까지. 모자란 칸은 왼쪽이 공백으로 찍힙니다.
