# temps[::-1]   거꾸로 뒤집은 새 목록. 콜론 두 개 뒤의 -1이 '한 칸씩 뒤로'
# temps[::-1][:3]   뒤집고 나서 앞에 3개 = 원래 목록의 마지막 3개를 거꾸로 본 것

